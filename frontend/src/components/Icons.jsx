export function Avatar({ name, size = 36 }) {
  const initials = (name || "?")
    .replace(/\([^)]*\)/g, "") // "Dr. Priya (Physio)" -> "Dr. Priya"
    .replace(/^(dr|mr|mrs|ms)\.?\s+/i, "")
    .replace(/[^\p{L}\s]/gu, "")
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0].toUpperCase())
    .join("");
  return (
    <span className="avatar" style={{ width: size, height: size, fontSize: size * 0.38 }}>
      {initials}
    </span>
  );
}
